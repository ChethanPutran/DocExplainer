"""What the tutor needs from the rest of the system, as Protocols. The orchestrator supplies adapters
over the knowledge graph, the learner model and the stores, so the tutor imports none of them."""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict, List, Optional, Protocol, Sequence, Tuple

from ..common.knowledge import Concept
from ..common.learner import Belief, BeliefChange, LearnerProfile
from ..common.structure import DocumentStructure


@dataclass
class SectionConcepts:
    introduces: List[Concept] = field(default_factory=list)
    uses_earlier: List[Concept] = field(default_factory=list)


class KnowledgeReader(Protocol):
    def section_concepts(self, doc_id: str, structure: DocumentStructure, section_id: str) -> SectionConcepts: ...

    def concepts_in_text(self, doc_id: str, text: str, upto: int) -> List[Concept]: ...

    def concept(self, doc_id: str, concept_id: str) -> Optional[Concept]: ...

    def concepts_upto(self, doc_id: str, ordinal: int) -> List[Concept]: ...

    def prerequisites(self, doc_id: str, concept_id: str, depth: int, upto: int) -> List[Tuple[Concept, int]]: ...

    def glossary(self, doc_id: str, ordinal: int, concept_ids: Sequence[str]) -> Dict[str, str]: ...

    def diagnostic_candidates(self, doc_id: str) -> List[Concept]: ...


class LearnerPort(Protocol):
    def beliefs(self, user_id: str, doc_id: str, concept_ids: Sequence[str]) -> Dict[str, Belief]: ...

    def profile(self, user_id: str, doc_id: str) -> LearnerProfile: ...

    def start(self, user_id: str, doc_id: str, level: str, known_concept_ids: Sequence[str], onboarding: dict) -> LearnerProfile: ...

    def question_asked(self, user_id: str, doc_id: str, text: str, concept_ids: Sequence[str]) -> None: ...

    def explanation_feedback(self, user_id: str, doc_id: str, concept_ids: Sequence[str], verdict: str) -> None: ...

    def read_section(self, user_id: str, doc_id: str, concept_ids: Sequence[str]) -> None: ...

    def quiz_answer(self, user_id: str, doc_id: str, concept_id: str, correct: bool, difficulty: float) -> List[BeliefChange]: ...

    def plan_diagnostic(self, user_id: str, doc_id: str, candidates: Sequence[Tuple[str, int]], k: int,
                        asked: Sequence[str]) -> List[str]: ...

    def recalibrate(self, user_id: str, doc_id: str) -> LearnerProfile: ...

    def position(self, user_id: str, doc_id: str) -> Optional[int]: ...

    def advance_position(self, user_id: str, doc_id: str, ordinal: int) -> int: ...


class StructureSource(Protocol):
    def load(self, doc_id: str) -> DocumentStructure: ...
